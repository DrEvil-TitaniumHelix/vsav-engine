def crops():
    im = full_page("ed2scan", 1)
    cols = columns(im)
    os.makedirs(PACK, exist_ok=True)
    made = []
    for ci, (a, b) in enumerate(cols, start=1):
        h = im.size[1]
        y = 0
        k = 0
        while y < h:
            y1 = min(h, y + CHUNK_H)
            c = im.crop((a, y, b, y1))
            c = c.resize((int(c.size[0] * SCALE), int(c.size[1] * SCALE)), Image.LANCZOS)
            name = f"p1_col{ci}_{chr(ord('a') + k)}.png"
            c.save(os.path.join(PACK, name))
            made.append(name)
            print(f"{name}  x={a}..{b} y={y}..{y1}  -> {c.size[0]}x{c.size[1]}")
            if y1 >= h:
                break
            y = y1 - OVERLAP
            k += 1
    zoom(2, 1050, 1200, "zoom_map_B2", 4.0)
    zoom(2, 1170, 1400, "zoom_map_B", 3.0)
    return made


def zoom(ci, y0, y1, name, scale=3.0):
    im = full_page("ed2scan", 1)
    cols = columns(im)
    a, b = cols[ci - 1]
    c = im.crop((a, y0, b, y1))
    c = c.resize((int(c.size[0] * scale), int(c.size[1] * scale)), Image.LANCZOS)
    os.makedirs(PACK, exist_ok=True)
    p = os.path.join(PACK, f"{name}.png")
    c.save(p)
    print(f"{p} {c.size[0]}x{c.size[1]}")
    return p


